/** Generates CakeSupersBenchmark.scala: cakes of N self-typed traits, as in scala.reflect.internal.SymbolTable.
 *
 *  build/quick/bin/scala test/benchmarks/gen/CakeSupersGen.scala > test/benchmarks/src/main/scala/scala/tools/nsc/CakeSupersBenchmark.scala
 */
object CakeSupersGen {
  val Sizes = List(30, 60, 70, 100)
  val Classes = 8
  val Calls = 8

  def main(args: Array[String]): Unit = {
    val sb = new java.lang.StringBuilder
    def w(s: String): Unit = sb.append(s).append('\n')

    w(s"""// Generated by test/benchmarks/gen/CakeSupersGen.scala; do not edit.
         |package scala.tools.nsc
         |
         |import java.util.concurrent.TimeUnit
         |
         |import org.openjdk.jmh.annotations._
         |
         |/** The cost of calls between the traits of a cake, as in `scala.reflect.internal.SymbolTable`, by the number of
         | *  traits (the class's secondary supers) and the number of concrete classes the call sites see.
         | *
         | *  In a trait `T` with self type `U` (a class), an unqualified call to a member of another trait `T2` of the cake was
         | *  compiled as `checkcast T2; invokeinterface T2.m` on `this`; `viaTrait` makes that cast explicit, so that it keeps
         | *  measuring it once the compiler (STARR, for this project) casts to `U` instead. The cast checks `U`'s secondary supers:
         | *  JDK 23+ keeps them in a 63-slot hashed table, so beyond 62 interfaces it is full and a miss takes a linear scan;
         | *  before, a one-element cache that thrashes when the cast alternates between interfaces. C2 skips the check when the
         | *  cast's type profile shows one class, so the cost appears once several classes share the code (`classes` > 1), as
         | *  when Scaladoc, the presentation compiler or macro toolboxes run beside the compiler. `viaClass` makes the same
         | *  calls through `this.asInstanceOf[U]`: `checkcast U` (a primary supers check) and `invokevirtual`.
         | *
         | *  The bodies of `Hot`'s methods are not inlined (`-XX:CompileCommand=dontinline`), as the compiler's hot trait
         | *  methods are too big to be: inlined into a caller whose receiver is known to be a `U`, C2 would fold the casts away.
         | *  Only the bodies: the static `viaTrait$$` that the class's forwarder calls must stay inlinable, as it is in the
         | *  compiler, or its `invokespecial` of the body adds a receiver check against `Hot` (C2's `Parse::do_call`) that
         | *  would otherwise fold away.
         | */
         |@BenchmarkMode(Array(Mode.AverageTime))
         |@Fork(value = 1, jvmArgsAppend = Array("-Xms1G", "-Xmx1G", "-XX:CompileCommand=quiet", "-XX:CompileCommand=dontinline,*$$Hot::viaTrait", "-XX:CompileCommand=dontinline,*$$Hot::viaClass"))
         |@Threads(1)
         |@Warmup(iterations = 10, time = 1)
         |@Measurement(iterations = 10, time = 1)
         |@OutputTimeUnit(TimeUnit.NANOSECONDS)
         |@State(Scope.Benchmark)
         |class CakeSupersBenchmark {
         |  import CakeSupersBenchmark._
         |
         |  /** The number of traits in the cake, so its classes' secondary supers (plus one, `Hot`). */
         |  @Param(Array(${Sizes.map(n => s""""$n"""").mkString(", ")}))
         |  var traits: Int = _
         |
         |  /** How many concrete classes of the cake the receivers are drawn from (1 to $Classes). */
         |  @Param(Array("1", "4"))
         |  var classes: Int = _
         |
         |  private var receivers: Array[Root] = _
         |
         |  @Setup(Level.Trial) def setup(): Unit = {
         |    val random = new java.util.SplittableRandom(1)
         |    receivers = Array.fill(Receivers)(make(traits, random.nextInt(classes)))
         |  }
         |
         |  /** One op is one call; each call makes $Calls calls to other traits of the cake. */
         |  @Benchmark @OperationsPerInvocation(Receivers)
         |  def viaTrait(): Int = {
         |    val rs = receivers
         |    var sum = 0
         |    var i = 0
         |    while (i < rs.length) { sum += rs(i).viaTrait(i); i += 1 }
         |    sum
         |  }
         |
         |  @Benchmark @OperationsPerInvocation(Receivers)
         |  def viaClass(): Int = {
         |    val rs = receivers
         |    var sum = 0
         |    var i = 0
         |    while (i < rs.length) { sum += rs(i).viaClass(i); i += 1 }
         |    sum
         |  }
         |}
         |
         |object CakeSupersBenchmark {
         |  final val Receivers = 1024
         |
         |  abstract class Root {
         |    def viaTrait(x: Int): Int
         |    def viaClass(x: Int): Int
         |  }
         |
         |  def make(traits: Int, cls: Int): Root = traits match {
         |${Sizes.map(n => s"    case $n => CakeSupers$n.make(cls)").mkString("\n")}
         |  }
         |}
         |""".stripMargin)

    // Top-level, as Java 8's Class.getSimpleName, which JMH calls, fails for classes in nested objects (JDK-8057919)
    for (n <- Sizes) {
      val called = (0 until Calls).map(k => 1 + (k * (n - 1)) / (Calls - 1)) // spread over the cake, first to last
      w(s"\nobject CakeSupers$n {")
      w("  import CakeSupersBenchmark.Root")
      w("  abstract class U extends Root\n" + (1 to n).map(i => s"    with T$i\n").mkString + "    with Hot")
      for (i <- 1 to n)
        w(s"  trait T$i { self: U => def f$i(x: Int): Int = x + $i }")
      w("  trait Hot { self: U =>")
      w("    def viaTrait(x: Int): Int = " + called.map(i => s"this.asInstanceOf[T$i].f$i(x)").mkString(" ^ "))
      w("    def viaClass(x: Int): Int = { val u = this.asInstanceOf[U]; " + called.map(i => s"u.f$i(x)").mkString(" ^ ") + " }")
      w("  }")
      for (c <- 0 until Classes)
        w(s"  final class C$c extends U")
      w("  def make(cls: Int): Root = cls match {")
      for (c <- 0 until Classes)
        w(s"    case $c => new C$c")
      w("  }")
      w("}")
    }
    print(sb)
  }
}
